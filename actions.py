def match_action(text: str):
    """
    Возвращает (stat, base_dc, skill_name, fail_event) или None.
    Приоритет: точное совпадение → вхождение подстроки.
    """
    text = text.lower().strip()

    # Точное совпадение
    if text in ACTION_CHECKS:
        return ACTION_CHECKS[text]

    # Вхождение подстроки
    for key, val in ACTION_CHECKS.items():
        if key in text:
            return val

    return None


def is_no_check(text: str) -> bool:
    """True, если фраза не должна вызывать проверку."""
    return text.lower().strip() in NO_CHECK_PHRASES


# ─── Динамический DC ───────────────────────────────

def calc_dc(base_dc: int, tension: int, attempts: int = 0) -> int:
    """
    Гибкая сложность:
    - напряжение: каждые 20 единиц дают +1 к DC
    - повторные попытки: каждая следующая +2 к DC (усталость/шум)
    """
    dc = base_dc
    dc += tension // 20
    dc += max(0, attempts - 1) * 2
    return min(dc, 25)  # потолок — 25, чтобы не было невозможного


# ─── Последствия ────────────────────────────────────

def get_consequences(result: dict) -> dict:
    """
    Возвращает структуру последствий для director и AI:
    - tension_delta: на сколько изменить напряжение
    - event: какое событие запустить (или None)
    - hint: подсказка для AI-промпта
    """
    crit = result.get("crit", False)
    fumble = result.get("fumble", False)
    success = result["success"]
    fail_event = result.get("fail_event")

    if crit:
        return {
            "tension_delta": -5,     # критический успех снимает напряжение
            "event": "crit_success",
            "hint": "КРИТИЧЕСКИЙ УСПЕХ! Игрок блестяще справился. Награди его: неожиданная находка, скрытый путь, бонус к следующему действию. Опиши триумф ярко.",
        }

    if fumble:
        return {
            "tension_delta": +15,    # критический провал — катастрофа
            "event": fail_event or "fumble",
            "hint": "КРИТИЧЕСКИЙ ПРОВАЛ! Катастрофа. Что-то пошло ужасно не так: сломанная отмычка, шум, привлекший врагов, травма. Опиши последствия жёстко, но не убивай игрока.",
        }

    if success:
        return {
            "tension_delta": +2,     # успех — небольшой рост
            "event": None,
            "hint": "Успех. Игрок справился с задачей. Опиши результат уверенно: что он нашёл, открыл, обнаружил. Без преувеличений.",
        }

    # Обычный провал
    return {
        "tension_delta": +8,        # провал — заметный рост напряжения
        "event": fail_event,
        "hint": "Провал. Действие не удалось, но это не катастрофа. Опиши, что пошло не так: упущенная деталь, скрипнувшая половица, несработавший довод. Намекни на последствия, но оставь путь дальше.",
    }


def build_ai_prompt(result: dict, consequences: dict, director) -> str:
    """Собирает промпт для AI с учётом результата и последствий."""
    ctx = director.get_context()
    status = result.get("crit") and "критический успех" or \
             result.get("fumble") and "критический провал" or \
             result["success"] and "успех" or "провал"

    return (
        f"Проверка: {result['stat_name']}, DC {result['dc']}, "
        f"Бросок: {result['roll']['total']}, {status}.\n"
        f"Мир: {ctx['setting']}\n"
        f"Текущая цель: {ctx['current_milestone']}\n"
        f"Напряжение: {ctx['tension']}/100\n"
        f"Указание: {consequences['hint']}"
    )
