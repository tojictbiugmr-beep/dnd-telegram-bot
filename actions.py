def match_action(text: str):
    """
    Возвращает (stat, dc, skill_name) если фраза подходит под действие.
    Иначе возвращает None.
    Приоритет: точное совпадение → вхождение подстроки.
    """
    text = text.lower().strip()

    # 1. Точное совпадение
    if text in ACTION_CHECKS:
        return ACTION_CHECKS[text]

    # 2. Вхождение ключевых слов (чтобы «крадусь в тени» сработало как «крадусь»)
    for key, val in ACTION_CHECKS.items():
        if key in text:
            return val

    return None
